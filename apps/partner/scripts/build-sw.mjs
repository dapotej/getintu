// After `next build`, writes out/sw.js: a service worker that keeps every file of the static
// scanner, so it opens and scans with no signal. A new build changes the cache name, and the
// old cache is dropped once the new worker takes over.
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const out = new URL("../out/", import.meta.url).pathname;

async function files(dir) {
  const entries = await readdir(dir);
  const nested = await Promise.all(entries.map(async (e) => ((await stat(join(dir, e))).isDirectory() ? files(join(dir, e)) : [join(dir, e)])));
  return nested.flat();
}

const all = (await files(out)).filter((f) => !f.endsWith(".txt") && !f.endsWith("sw.js") && !f.includes(`${sep}404`));
const hash = createHash("sha256");
for (const f of all) hash.update(await readFile(f));
const version = hash.digest("hex").slice(0, 12);
const urls = all.map((f) => "/" + relative(out, f).split(sep).join("/")).map((u) => (u === "/index.html" ? "/" : u));

const worker = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "intu-scanner-${version}";
const FILES = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("intu-scanner-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  // Only the scanner's own files; API calls always go to the network.
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // The page: fresh when there's signal, the cached copy when there isn't.
    event.respondWith(fetch(req).catch(() => caches.match("/", { ignoreSearch: true })));
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
await writeFile(join(out, "sw.js"), worker);
console.log(`Service worker: ${urls.length} files, cache intu-scanner-${version}`);
